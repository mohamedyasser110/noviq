<#
.SYNOPSIS
    One-command Noviq deployment to Railway (two services: api + web).

.DESCRIPTION
    Wraps the whole sequence documented in docs/DEPLOYMENT-RAILWAY.md:
    create the project, create both services, set every variable, attach the
    SQLite volume, deploy the API, read its public domain, deploy the web
    tier against that domain, then point CORS back at the web domain.

    It is safe to re-run. Railway is declarative: linking an existing
    project/service and re-setting the same variables is a no-op, so this
    doubles as the "fix the deploy" script.

.PARAMETER Project
    Railway project name. Created if it does not exist.

.PARAMETER SkipWeb
    Deploy only the API tier (useful to debug the web build alone).

.PARAMETER MigrateDb
    Also push backend\data\noviq.db onto the volume so the deployed
    content matches this machine instead of the shipped seed defaults.

.EXAMPLE
    .\deploy-railway.ps1
    .\deploy-railway.ps1 -MigrateDb
#>
[CmdletBinding()]
param(
    [string]$Project = 'noviq',
    [switch]$SkipWeb,
    [switch]$MigrateDb
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# The CLI is installed with `npm i -g @railway/cli`, which on this machine
# lands in C:\npm-global — add it explicitly so a fresh shell works too.
if (-not (Get-Command railway -ErrorAction SilentlyContinue)) {
    $npmGlobal = 'C:\npm-global'
    if (Test-Path (Join-Path $npmGlobal 'railway.cmd')) {
        $env:PATH = "$npmGlobal;$env:PATH"
    }
}

$Root      = $PSScriptRoot
$ApiDir    = Join-Path $Root 'backend'
$WebDir    = Join-Path $Root 'frontend'
$ApiSvc    = 'api'
$WebSvc    = 'web'

function Step  ($m) { Write-Host "`n=== $m ===" -ForegroundColor Cyan }
function Info  ($m) { Write-Host "    $m" }
function Fail  ($m) { Write-Host "FAILED: $m" -ForegroundColor Red; exit 1 }

# --------------------------------------------------------------------------
# 0. Preflight
# --------------------------------------------------------------------------
Step 'Preflight'
if (-not (Get-Command railway -ErrorAction SilentlyContinue)) { Fail 'railway CLI not on PATH' }
$who = railway whoami 2>&1
if ($LASTEXITCODE -ne 0 -or $who -match 'Unauthorized') {
    Fail @"
railway CLI is not authenticated. Run:

    railway login

(or set RAILWAY_TOKEN from https://railway.com/account/tokens)
and then re-run this script.
"@
}
Info "authenticated as: $who"

# --------------------------------------------------------------------------
# Secrets — reused from .env.railway if present so re-runs keep working.
# A rotated JWT_SECRET invalidates every issued admin session, so this file
# is the source of truth after the first run. It is gitignored.
# --------------------------------------------------------------------------
$secretFile = Join-Path $Root '.env.railway'
if (Test-Path $secretFile) {
    Info "reusing secrets from .env.railway"
    Get-Content $secretFile | ForEach-Object {
        if ($_ -match '^\s*([A-Z0-9_]+)=(.*)$') { Set-Item -Path "env:$($matches[1])" -Value $matches[2] }
    }
} else {
    Info 'generating fresh secrets'
    $bytes = { param($n) -join ((1..$n) | ForEach-Object { '{0:x}' -f (Get-Random -Maximum 16) }) }
    $env:JWT_SECRET        = 'noviq_' + (& $bytes 64)
    $env:REVALIDATE_SECRET = 'noviq_rev_' + (& $bytes 48)
    $env:ADMIN_PASSWORD    = 'Nv' + (& $bytes 24) + '!7'
    @(
        '# Noviq production secrets — generated by deploy-railway.ps1'
        '# Delete this file to rotate on the next run. NEVER commit it.'
        "JWT_SECRET=$($env:JWT_SECRET)"
        "REVALIDATE_SECRET=$($env:REVALIDATE_SECRET)"
        "ADMIN_PASSWORD=$($env:ADMIN_PASSWORD)"
    ) | Set-Content -Path $secretFile -Encoding utf8
    Info "secrets written to $secretFile"
}

# --------------------------------------------------------------------------
# 1. Project
# --------------------------------------------------------------------------
Step "Project: $Project"
Push-Location $ApiDir
$linkOut = railway link -s $ApiSvc 2>&1
if ($LASTEXITCODE -ne 0) {
    Info 'link failed — creating the project'
    railway init 2>&1 | Write-Host
    if ($LASTEXITCODE -ne 0) { Pop-Location; Fail 'railway init failed' }
    railway link -s $ApiSvc 2>&1 | Write-Host
}
Pop-Location

# --------------------------------------------------------------------------
# 2. API variables
# --------------------------------------------------------------------------
Step 'API variables'
Push-Location $ApiDir
$apiVars = [ordered]@{
    NODE_ENV              = 'production'
    PORT                  = '4322'
    STORAGE_DIR           = '/app/storage'
    DB_PATH               = '/app/storage/noviq.db'
    UPLOADS_DIR           = '/app/storage/uploads'
    JWT_SECRET            = $env:JWT_SECRET
    ADMIN_PASSWORD        = $env:ADMIN_PASSWORD
    REVALIDATE_SECRET     = $env:REVALIDATE_SECRET
    FRONTEND_URL          = ''      # filled in once the web domain exists
    FRONTEND_REVALIDATE_URL = ''    # ditto
}
foreach ($k in $apiVars.Keys) { railway variables set --kv "$k=$($apiVars[$k])" 2>&1 | Out-Null }
Info 'api variables set'
Pop-Location

# --------------------------------------------------------------------------
# 3. Volume — SQLite + uploads
# --------------------------------------------------------------------------
Step 'Volume'
Push-Location $ApiDir
$volumes = railway volume ls --json 2>&1 | ConvertFrom-Json
if (-not ($volumes | Where-Object { $_.mountPath -eq '/app/storage' })) {
    railway volume add --mount-path /app/storage 2>&1 | Write-Host
} else {
    Info 'volume already attached at /app/storage'
}
Pop-Location

# --------------------------------------------------------------------------
# 4. Deploy the API
# --------------------------------------------------------------------------
Step 'Deploy api'
Push-Location $ApiDir
railway up 2>&1 | Write-Host
if ($LASTEXITCODE -ne 0) { Pop-Location; Fail 'api deploy failed' }
Pop-Location

Step 'API public domain'
Push-Location $ApiDir
$apiDomain = (railway domain 2>&1 | Select-String -Pattern '([a-z0-9-]+\.up\.railway\.app)' | Select-Object -First 1).Matches.Groups[1].Value
Pop-Location
if (-not $apiDomain) { Fail 'could not read the API domain — check `railway domain` output' }
$apiOrigin = "https://$apiDomain"
Info "api origin: $apiOrigin"

# Railway's private network address: same-project services reach each other
# at <service>.internal without leaving the private network. Using it for
# API_INTERNAL_URL keeps the internal hostname out of the browser bundle.
$apiInternal = "http://$ApiSvc.internal:4322"

# --------------------------------------------------------------------------
# 5. Web service
# --------------------------------------------------------------------------
if ($SkipWeb) { Info '-SkipWeb set — stopping before the web tier'; return }

Step "Web service: $WebSvc"
Push-Location $WebDir
$webLink = railway link -s $WebSvc 2>&1
if ($LASTEXITCODE -ne 0) {
    Info 'link failed — creating the service'
    railway add $WebSvc 2>&1 | Write-Host
    railway link -s $WebSvc 2>&1 | Write-Host
}

# NEXT_PUBLIC_API_URL is inlined at build time, so it must be set BEFORE
# `up` — the prerender talks to the API while the image is being built.
$webVars = [ordered]@{
    NEXT_PUBLIC_API_URL = $apiOrigin
    API_INTERNAL_URL    = $apiInternal
    REVALIDATE_SECRET   = $env:REVALIDATE_SECRET
    NODE_ENV            = 'production'
}
foreach ($k in $webVars.Keys) { railway variables set --kv "$k=$($webVars[$k])" 2>&1 | Out-Null }
Info 'web variables set'

railway up 2>&1 | Write-Host
if ($LASTEXITCODE -ne 0) { Pop-Location; Fail 'web deploy failed' }

$webDomain = (railway domain 2>&1 | Select-String -Pattern '([a-z0-9-]+\.up\.railway\.app)' | Select-Object -First 1).Matches.Groups[1].Value
if (-not $webDomain) { Pop-Location; Fail 'could not read the web domain' }
$webOrigin = "https://$webDomain"
Pop-Location
Info "web origin: $webOrigin"

# --------------------------------------------------------------------------
# 6. Close the CORS loop — the web domain only exists after step 5
# --------------------------------------------------------------------------
Step 'Point CORS at the web domain'
Push-Location $ApiDir
railway variables set --kv "FRONTEND_URL=$webOrigin" 2>&1 | Out-Null
railway variables set --kv "FRONTEND_REVALIDATE_URL=$webOrigin" 2>&1 | Out-Null
Pop-Location
Info 'api restarted with the new CORS origin'

# --------------------------------------------------------------------------
# 7. Optional database migration
# --------------------------------------------------------------------------
if ($MigrateDb) {
    Step 'Migrate the local database onto the volume'
    Push-Location (Join-Path $ApiDir 'scripts')
    node snapshot-db.js 2>&1 | Write-Host
    if ($LASTEXITCODE -ne 0) { Pop-Location; Fail 'snapshot-db.js failed' }
    $db = Join-Path $ApiDir 'data\noviq.db'
    Info "uploading $((Get-Item $db).Length / 1MB) MB to /app/storage/noviq.db"
    Get-Content -AsByteStream -ReadCount 0 $db |
        railway ssh "cat > /app/storage/noviq.db && chown node:node /app/storage/noviq.db" 2>&1 | Write-Host
    railway restart 2>&1 | Write-Host
    Pop-Location
    Info 'uploads are separate files — copy frontend\public\images\uploads\ or re-upload via /admin'
}

# --------------------------------------------------------------------------
# 8. Verify
# --------------------------------------------------------------------------
Step 'Verify'
Start-Sleep -Seconds 20
foreach ($u in @("$apiOrigin/api/health", "$webOrigin/en", "$webOrigin/api/health")) {
    try {
        $r = Invoke-WebRequest -Uri $u -UseBasicParsing -TimeoutSec 30
        Info ("{0,-6} {1}" -f $r.StatusCode, $u)
    } catch {
        Info ("FAIL   {0}  ({1})" -f $u, $_.Exception.Message)
    }
}

Write-Host "`n=== Done ===" -ForegroundColor Green
Write-Host "  site    $webOrigin"
Write-Host "  api     $apiOrigin"
Write-Host "  admin   $apiOrigin/admin   (user: admin)"
Write-Host "  pw      $env:ADMIN_PASSWORD"
Write-Host "`n  Secrets are stored in $secretFile"
