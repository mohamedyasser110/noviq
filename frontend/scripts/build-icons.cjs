/* Generate lib/icons.ts: one verified entry per icon name the site ships.
   Every component is checked against the installed lucide-react before it is
   written, so a name that cannot be imported fails here instead of rendering
   as a "?" in the UI. */
const fs = require('fs');
const path = require('path');

const ROOT = 'C:/Downloads/Noviq - final/frontend';
const lucide = require(path.join(ROOT, 'node_modules/lucide-react'));

const config = fs.readFileSync(path.join(ROOT, 'data/content.config.js'), 'utf8');
const utils = fs.readFileSync(path.join(ROOT, 'lib/utils.ts'), 'utf8');

const names = new Set([...config.matchAll(/"icon":\s*"([^"]+)"/g)].map((m) => m[1]));
for (const m of utils.matchAll(/(?:^|\s)'?([a-z0-9-]+)'?:\s*[A-Z][A-Za-z0-9]*,/g)) names.add(m[1]);

const pascal = (k) => k.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');

/* Two shipped names are not lucide names at all: "arrow" and "design" are
   editorial shorthands the dashboard has always used. */
const ALIASES = { arrow: 'ArrowRight', design: 'PenTool' };

const entries = [];
const skipped = [];
for (const name of [...names].sort()) {
  const direct = pascal(name);
  const target = ALIASES[name] || direct;
  if (typeof lucide[target] !== 'undefined') entries.push([name, target]);
  else skipped.push(name + ' -> ' + target);
}

const imports = [...new Set(entries.map((e) => e[1]))].sort();
const lines = [];
lines.push('/* GENERATED by scripts/build-icons â€” see the footer note before editing.');
lines.push(' *');
lines.push(' * Every icon name the site can be asked to render comes from CMS content,');
lines.push(' * so a name the map does not know silently fell through to HelpCircle â€” a');
lines.push(' * literal "?" sitting in the middle of a card. That reads as broken data');
lines.push(' * rather than a missing glyph, and it shipped that way for several');
lines.push(' * solutions and industries.');
lines.push(' *');
lines.push(' * So the list is derived from the names the content actually ships and each');
lines.push(' * component is verified against the installed lucide-react. Add an icon by');
lines.push(' * adding its lucide name to the content, then re-running the generator:');
lines.push(' *');
lines.push(' *     node scripts/build-icons.cjs');
lines.push(' *');
lines.push(' * Only two entries are not lucide names â€” "arrow" and "design" are');
lines.push(' * editorial shorthands the dashboard has always used.');
lines.push(' */');
lines.push("import {");
for (let i = 0; i < imports.length; i += 4) {
  lines.push('  ' + imports.slice(i, i + 4).join(', ') + ',');
}
lines.push("} from 'lucide-react';");
lines.push('');
lines.push('export const iconMap: Record<string, React.ComponentType<{ size?: number; className?: string }>> = {');
for (const [name, target] of entries) {
  const key = /^[a-z][a-zA-Z0-9]*$/.test(name) ? name : "'" + name + "'";
  lines.push('  ' + key + ': ' + target + ',');
}
lines.push('};');
lines.push('');
lines.push('/** Names the site can actually draw. The admin icon picker should read this');
lines.push(' * list, so the operator picks from what renders instead of guessing lucide');
lines.push(' * names and discovering the "?" fallback afterwards. */');
lines.push('export const supportedIconNames = Object.keys(iconMap).sort();');
lines.push('');
lines.push('export function hasIcon(name: string): boolean {');
lines.push("  return Object.prototype.hasOwnProperty.call(iconMap, String(name || '').toLowerCase());");
lines.push('}');
lines.push('');

fs.writeFileSync(path.join(ROOT, 'lib/icons.ts'), lines.join('\n'));

/* ---- keep the admin's picker in step -------------------------------
   The dashboard offered 215 icon names while the frontend could draw 90 of
   them, so 58% of a perfectly reasonable choice rendered as a literal "?" in
   the middle of a card — and it looked like broken data, not a missing
   glyph. The picker is the only place the operator can choose from, so it is
   the right place to stop: offer exactly what the site can draw.

   The curated list that used to live here (215 names, several of which were
   never lucide names at all) is what produced the gap. The generated list is
   a subset of it plus every name the content actually uses, so nothing that
   used to work stops working. */
const adminPath = 'C:/Downloads/Noviq - final/backend/admin/index.html';
const admin = fs.readFileSync(adminPath, 'utf8');
const startMark = 'const LUCIDE_ICONS = [';
const start = admin.indexOf(startMark);
if (start === -1) {
  console.log('admin: LUCIDE_ICONS not found — skipped');
} else {
  const open = admin.indexOf('[', start);
  const close = admin.indexOf('];', open);
  const previous = [...admin.slice(open, close).matchAll(/'([a-z0-9-]+)'/g)].map((m) => m[1]);
  const unique = [...new Set(previous)];
  const body = entries
    .map(([name]) => name)
    .sort()
    .reduce((acc, name, i) => {
      const line = i % 8 === 0 ? '\n  ' : ' ';
      return acc + line + "'" + name + "',";
    }, '[');
  const replacement =
    '/* GENERATED by frontend/scripts/build-icons.cjs -- every name here is\n' +
    '   verified importable from lucide AND present in lib/icons.ts, so a name\n' +
    '   the operator can pick is always a name the site can draw.\n' +
    '   Previously this listed ' + unique.length + ' curated names while the\n' +
    '   frontend could render far fewer, and the difference showed up on the\n' +
    '   page as a "?" glyph. Do not hand-edit; run the generator instead. */\n' +
    'const LUCIDE_ICONS = ' + body + '\n];';
  fs.writeFileSync(adminPath, admin.slice(0, start) + replacement + admin.slice(close + 2));
  console.log('admin picker: ' + previous.length + ' names -> ' + entries.length + ' verified');
}

console.log('entries:', entries.length, '| unique components:', imports.length);
console.log('skipped (not importable):', skipped.length ? skipped.join(', ') : 'none');